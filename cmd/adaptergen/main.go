// adaptergen creates an IoC-backed adapter for a Go interface in the same package.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type method struct {
	name       string
	parameters []string
	arguments  []string
	valueType  string
	key        string
}

func main() {
	name := flag.String("type", "", "interface name")
	output := flag.String("output", "", "generated file path")
	flag.Parse()
	if !token.IsIdentifier(*name) || *output == "" {
		fmt.Fprintln(os.Stderr, "usage: adaptergen -type InterfaceName -output generated.go")
		os.Exit(2)
	}
	source, err := generateSource(".", *name)
	if err == nil {
		err = os.WriteFile(*output, source, 0644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generateSource(dir, interfaceName string) ([]byte, error) {
	files, err := parser.ParseDir(token.NewFileSet(), dir, func(info os.FileInfo) bool {
		return strings.HasSuffix(info.Name(), ".go") && !strings.HasSuffix(info.Name(), "_test.go")
	}, 0)
	if err != nil {
		return nil, err
	}
	var sourceFile *ast.File
	var target *ast.InterfaceType
	for _, pkg := range files {
		for _, file := range pkg.Files {
			for _, declaration := range file.Decls {
				group, ok := declaration.(*ast.GenDecl)
				if !ok {
					continue
				}
				for _, spec := range group.Specs {
					definition, ok := spec.(*ast.TypeSpec)
					if !ok || definition.Name.Name != interfaceName {
						continue
					}
					if sourceFile != nil {
						return nil, fmt.Errorf("duplicate type %s", interfaceName)
					}
					sourceFile = file
					target, _ = definition.Type.(*ast.InterfaceType)
				}
			}
		}
	}
	if sourceFile == nil {
		return nil, fmt.Errorf("type %s not found in %s", interfaceName, dir)
	}
	if target == nil {
		return nil, fmt.Errorf("%s is not an interface", interfaceName)
	}

	methods := make([]method, 0, len(target.Methods.List))
	usedImports := make(map[string]bool)
	for _, field := range target.Methods.List {
		if len(field.Names) != 1 {
			return nil, fmt.Errorf("%s: embedded or grouped methods are unsupported", interfaceName)
		}
		signature, ok := field.Type.(*ast.FuncType)
		if !ok {
			return nil, fmt.Errorf("%s: invalid method %s", interfaceName, field.Names[0].Name)
		}
		entry, err := parseMethod(field.Names[0].Name, interfaceName, signature, usedImports)
		if err != nil {
			return nil, err
		}
		methods = append(methods, entry)
	}
	imports, err := requiredImports(sourceFile, usedImports)
	if err != nil {
		return nil, err
	}

	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by adaptergen; DO NOT EDIT.")
	fmt.Fprintf(&out, "package %s\n\n", sourceFile.Name.Name)
	fmt.Fprintln(&out, "import (")
	fmt.Fprintln(&out, "\"reflect\"")
	for _, name := range imports {
		fmt.Fprintln(&out, name)
	}
	fmt.Fprint(&out, ")\n\n")
	fmt.Fprintf(&out, "type %sAdapter struct {\n ioc *IoC\n session *ScopeSession\n object any\n}\n\n", interfaceName)
	for _, entry := range methods {
		returnType := "error"
		if entry.valueType != "" {
			returnType = "(" + entry.valueType + ", error)"
		}
		fmt.Fprintf(&out, "func (adapter *%sAdapter) %s(%s) %s {\n", interfaceName, entry.name, strings.Join(entry.parameters, ", "), returnType)
		args := "adapter.object"
		if len(entry.arguments) > 0 {
			args += ", " + strings.Join(entry.arguments, ", ")
		}
		if entry.valueType != "" {
			fmt.Fprintf(&out, " return adapter.ioc.Resolve[%s](adapter.session, %q, %s)\n", entry.valueType, entry.key, args)
		} else {
			fmt.Fprintf(&out, " command, err := adapter.ioc.Resolve[Command](adapter.session, %q, %s)\n", entry.key, args)
			fmt.Fprintln(&out, " if err != nil { return err }")
			fmt.Fprintln(&out, " return command.Execute()")
		}
		fmt.Fprint(&out, "}\n\n")
	}
	fmt.Fprintf(&out, "var _ %s = (*%sAdapter)(nil)\n\n", interfaceName, interfaceName)
	fmt.Fprintf(&out, "func Register%sAdapter(registry *AdapterRegistry) error {\n", interfaceName)
	fmt.Fprintf(&out, " return registry.Register(reflect.TypeFor[%s](), func(ioc *IoC, session *ScopeSession, object any) any {\n", interfaceName)
	fmt.Fprintf(&out, "  return &%sAdapter{ioc: ioc, session: session, object: object}\n", interfaceName)
	fmt.Fprintln(&out, " })")
	fmt.Fprintln(&out, "}")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated adapter: %w", err)
	}
	return formatted, nil
}

func parseMethod(name, interfaceName string, signature *ast.FuncType, usedImports map[string]bool) (method, error) {
	entry := method{name: name}
	if signature.TypeParams != nil {
		return entry, fmt.Errorf("%s.%s: type parameters are unsupported", interfaceName, name)
	}
	if signature.Params != nil {
		for _, field := range signature.Params.List {
			if _, variadic := field.Type.(*ast.Ellipsis); variadic {
				return entry, fmt.Errorf("%s.%s: variadic arguments are unsupported", interfaceName, name)
			}
			typeName, err := expression(field.Type, usedImports)
			if err != nil {
				return entry, err
			}
			count := len(field.Names)
			if count == 0 {
				count = 1
			}
			for range count {
				argument := fmt.Sprintf("arg%d", len(entry.arguments))
				entry.parameters = append(entry.parameters, argument+" "+typeName)
				entry.arguments = append(entry.arguments, argument)
			}
		}
	}
	var results []ast.Expr
	if signature.Results != nil {
		for _, field := range signature.Results.List {
			count := len(field.Names)
			if count == 0 {
				count = 1
			}
			for range count {
				results = append(results, field.Type)
			}
		}
	}
	if len(results) < 1 || len(results) > 2 || !isError(results[len(results)-1]) {
		return entry, fmt.Errorf("%s.%s: expected error or (value, error) result", interfaceName, name)
	}
	if len(results) == 2 {
		var err error
		entry.valueType, err = expression(results[0], usedImports)
		if err != nil {
			return entry, err
		}
	}
	property := name
	operation := "call"
	if strings.HasPrefix(name, "Set") && len(name) > 3 && len(entry.arguments) == 1 {
		property = name[3:]
		operation = "set"
	} else if len(entry.arguments) == 0 && entry.valueType != "" {
		operation = "get"
	}
	property = strings.ToLower(property[:1]) + property[1:]
	entry.key = interfaceName + ":" + property + "." + operation
	return entry, nil
}

func isError(expr ast.Expr) bool {
	name, ok := expr.(*ast.Ident)
	return ok && name.Name == "error"
}

func expression(expr ast.Expr, usedImports map[string]bool) (string, error) {
	var out bytes.Buffer
	if err := format.Node(&out, token.NewFileSet(), expr); err != nil {
		return "", err
	}
	ast.Inspect(expr, func(node ast.Node) bool {
		selector, ok := node.(*ast.SelectorExpr)
		if ok {
			if prefix, ok := selector.X.(*ast.Ident); ok {
				usedImports[prefix.Name] = true
			}
		}
		return true
	})
	return out.String(), nil
}

func requiredImports(file *ast.File, used map[string]bool) ([]string, error) {
	var imports []string
	for _, spec := range file.Imports {
		path, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			return nil, err
		}
		alias := filepath.Base(path)
		if spec.Name != nil {
			alias = spec.Name.Name
		}
		if !used[alias] {
			continue
		}
		delete(used, alias)
		if path == "reflect" && alias == "reflect" {
			continue
		}
		if spec.Name != nil {
			imports = append(imports, alias+" "+spec.Path.Value)
		} else {
			imports = append(imports, spec.Path.Value)
		}
	}
	if len(used) > 0 {
		var names []string
		for name := range used {
			names = append(names, name)
		}
		sort.Strings(names)
		return nil, errors.New("unresolved package qualifiers: " + strings.Join(names, ", "))
	}
	sort.Strings(imports)
	return imports, nil
}
